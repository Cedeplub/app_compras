    'Margem alvo do atacado que estava vigente antes desta substituição. NULL = a linha arquivada não tinha margem de atacado decidida (mesma semântica de APP_DECISAO_PRECO.margem_alvo). CHECK entre -1 e 1.';
comment on column app_decisao_preco_hist.margem_alvo_varejo is
    'Margem alvo do varejo que estava vigente antes desta substituição. NULL = a linha arquivada não tinha margem de varejo decidida. CHECK entre -1 e 1.';
comment on column app_decisao_preco_hist.alt_pv_at_av is
    'Preço final de atacado que estava vigente antes desta substituição (pode ser NULL, mesma semântica de APP_DECISAO_PRECO.alt_pv_at_av). CHECK > 0 quando não nulo.';
comment on column app_decisao_preco_hist.alt_pv_var_av is
    'Preço final de varejo que estava vigente antes desta substituição (pode ser NULL). CHECK > 0 quando não nulo.';
comment on column app_decisao_preco_hist.atualizado_em is
    'ATUALIZADO_EM original, copiado da linha de APP_DECISAO_PRECO no momento em que ela foi substituída — quando aquele valor passou a valer, não quando foi arquivado.';
comment on column app_decisao_preco_hist.atualizado_por is
    'ATUALIZADO_POR original, copiado da linha de APP_DECISAO_PRECO no momento da substituição.';
