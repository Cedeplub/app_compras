comment on column app_decisao_preco_hist.id_hist is
    'Chave técnica sequencial (IDENTITY, GENERATED ALWAYS — nunca aceita id explícito em uso normal), sem significado de negócio.';
comment on column app_decisao_preco_hist.id_produto is
