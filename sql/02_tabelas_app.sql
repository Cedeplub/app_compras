comment on column app_decisao_preco.margem_alvo is
    'Margem alvo decidida para o atacado, fração decimal (0.20 = 20%; CHECK entre -1 e 1 — quem digitar "20" achando que é 20% recebe erro em vez de gravar 2000%). NULL = sem decisão humana registrada; o padrão de 20% (CONTEXTO.md §6 regra 10) é aplicado pelo dbt fora desta tabela, nunca gravado aqui como default.';
comment on column app_decisao_preco.margem_alvo_varejo is
    'Margem alvo decidida para o varejo (filiais fora de 02/09), fração decimal, mesma semântica de NULL e mesmo CHECK entre -1 e 1 de MARGEM_ALVO.';
comment on column app_decisao_preco.alt_pv_at_av is
    'Preço de venda final decidido para o atacado (ALT_PV_AT_AV). CHECK > 0 quando não nulo. NULL = ainda sem decisão humana registrada para este campo; nunca é preenchido automaticamente com uma sugestão do modelo (CONTEXTO.md §6 regra 10).';
comment on column app_decisao_preco.alt_pv_var_av is
    'Preço de venda final decidido para o varejo (ALT_PV_VAR_AV). CHECK > 0 quando não nulo. Mesma semântica de NULL que ALT_PV_AT_AV.';
comment on column app_decisao_preco.atualizado_em is
    'Timestamp da última gravação desta linha (não da criação).';
comment on column app_decisao_preco.atualizado_por is
    'Login (APP_USUARIO.login) de quem gravou o valor vigente.';

