-- 3. APP_DECISAO_PEDIDO — quantidade de pedido decidida por produto.
--
-- PEDIDO é digitado pelo comprador na UNIDADE DE EXIBIÇÃO do produto — a
-- mesma unidade mostrada na tela, equivalente à coluna BA (PEDIDO) da
-- planilha original. Essa unidade não é fixa: na planilha,
-- PEDIDO_UNIDADES (coluna BB) = PEDIDO x FATOR_EXIBICAO, e FATOR_EXIBICAO
-- (coluna K) é IF(dFornecedor.PEDIDO_EM='MASTER', EMBAL_COMPRA, 1) — um valor
-- que não mora nesta tabela e que muda quando o cadastro do fornecedor ou do
-- produto muda (CONTEXTO.md §6 regra 6). Se só guardássemos PEDIDO, uma
-- mudança de cadastro depois da gravação mudaria retroativamente o
-- significado da mesma linha, sem que ninguém a tivesse tocado. Por isso a
-- tabela também guarda FATOR_EXIBICAO: o fator vigente no INSTANTE da
-- decisão, congelado de propósito. A quantidade em unidades sempre se
-- recalcula a partir desta linha (PEDIDO x FATOR_EXIBICAO), nunca lendo o
-- fator do cadastro atual.
--------------------------------------------------------------------------------
declare
    v_existe number;
begin
    select count(*) into v_existe from user_tables where table_name = 'APP_DECISAO_PEDIDO';
    if v_existe = 0 then
        execute immediate q'[
            create table app_decisao_pedido (
                id_produto      number(10)      not null,
                pedido          number(14,4)     not null,
                fator_exibicao  number(14,6)     not null,
                atualizado_em   timestamp        default systimestamp not null,
                atualizado_por  varchar2(60)     not null,
                constraint pk_app_decisao_pedido primary key (id_produto),
                constraint ck_app_decisao_pedido_ped
                    check (pedido >= 0),
                constraint ck_app_decisao_pedido_fat
                    check (fator_exibicao > 0)
            )
        ]';
    end if;
end;
/

comment on table app_decisao_pedido is
    'Quantidade de pedido de compra decidida por produto. Uma linha por SKU com pedido gravado manualmente; SKU sem linha significa "sem pedido decidido ainda" e o dbt usa a sugestão calculada em fat_pedido. PEDIDO está na UNIDADE DE EXIBIÇÃO (equivalente à coluna BA da planilha), não na unidade de estoque; a quantidade em unidades = PEDIDO x FATOR_EXIBICAO, onde FATOR_EXIBICAO é o fator (dFornecedor.PEDIDO_EM / EMBAL_COMPRA — CONTEXTO.md §6 regra 6) vigente no instante em que esta linha foi gravada, congelado de propósito: ele vive fora desta tabela, no cadastro, e pode mudar depois — recalculá-lo no presente mudaria o significado de uma decisão já tomada.';
comment on column app_decisao_pedido.id_produto is
    'CODPROD do CEDEP (cedep.pcprodut.codprod). Sem FK física para o CEDEP (fronteira do projeto).';
comment on column app_decisao_pedido.pedido is
    'Quantidade de pedido decidida pelo comprador, EXATAMENTE como digitada, na unidade de exibição (coluna BA da planilha) — não é a unidade de estoque/unidades. CHECK >= 0. Para a quantidade em unidades, multiplicar por FATOR_EXIBICAO desta mesma linha (nunca pelo fator atual do cadastro).';
comment on column app_decisao_pedido.fator_exibicao is
    'Snapshot do fator de conversão vigente no instante da gravação (equivalente à coluna K/FATOR_EXIBICAO da planilha: EMBAL_COMPRA quando dFornecedor.PEDIDO_EM=MASTER, senão 1). CHECK > 0. Congelado de propósito: PEDIDO_UNIDADES desta linha = PEDIDO x FATOR_EXIBICAO, os dois sempre lidos juntos desta mesma linha, nunca recalculando a partir do cadastro atual — que pode ter mudado depois desta decisão.';
comment on column app_decisao_pedido.atualizado_em is
    'Timestamp da última gravação desta linha.';
comment on column app_decisao_pedido.atualizado_por is
    'Login (APP_USUARIO.login) de quem gravou o pedido vigente.';

