-- 2. APP_DECISAO_PRECO_HIST — todo valor anterior de APP_DECISAO_PRECO.
--
-- Antes de sobrescrever uma linha em APP_DECISAO_PRECO, a aplicação grava o
-- valor que está saindo aqui. DECIDIDO_EM é o instante desse arquivamento
-- (quando o valor deixou de valer), não o instante em que ele foi criado —
-- esse já está em ATUALIZADO_EM, copiado da linha original. MARGEM_ALVO e
-- MARGEM_ALVO_VAREJO são NULLABLE aqui pela mesma razão que em
-- APP_DECISAO_PRECO: uma linha arquivada pode ter sido gravada só com preço,
-- sem margem decidida, e o histórico precisa preservar esse NULL, não
-- inventar um valor.
--------------------------------------------------------------------------------
declare
    v_existe number;
begin
    select count(*) into v_existe from user_tables where table_name = 'APP_DECISAO_PRECO_HIST';
    if v_existe = 0 then
        execute immediate q'[
            create table app_decisao_preco_hist (
                id_hist              number         generated always as identity,
                id_produto           number(10)      not null,
                margem_alvo          number(9,6),
                margem_alvo_varejo   number(9,6),
                alt_pv_at_av         number(14,4),
                alt_pv_var_av        number(14,4),
                atualizado_em        timestamp        not null,
                atualizado_por       varchar2(60)     not null,
                decidido_em          timestamp        default systimestamp not null,
                constraint pk_app_decisao_preco_hist primary key (id_hist),
                constraint ck_app_decisao_preco_h_ma
                    check (margem_alvo between -1 and 1),
                constraint ck_app_decisao_preco_h_mav
                    check (margem_alvo_varejo between -1 and 1),
                constraint ck_app_decisao_preco_h_pv
                    check (alt_pv_at_av > 0),
                constraint ck_app_decisao_preco_h_pvv
                    check (alt_pv_var_av > 0)
            )
        ]';
    end if;
end;
