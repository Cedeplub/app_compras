--------------------------------------------------------------------------------
-- 02_tabelas_app.sql
--
-- Cria as tabelas APP_* no schema COMPRAS: tudo que a aplicação (dashboard)
-- escreve. O dbt nunca cria nem derruba nada com prefixo APP_ (CONTEXTO.md §2).
--
-- Idempotente: cada CREATE TABLE é precedido de uma checagem em USER_TABLES,
-- então rodar o script de novo não derruba dado nenhum. Evolução de schema
-- (nova coluna, novo índice) é ALTER separado, num script de migração à
-- parte — nunca editado aqui depois de publicado.
--
-- Colunas IDENTITY (APP_DECISAO_PRECO_HIST.ID_HIST, APP_USUARIO.ID_USUARIO,
-- APP_AUDITORIA.ID_AUDITORIA) usam GENERATED ALWAYS AS IDENTITY, de propósito
-- e não GENERATED BY DEFAULT: BY DEFAULT aceita um id explícito no INSERT sem
-- avançar a sequência interna, o que mais cedo ou mais tarde bate de frente
-- com um valor gerado depois e falha com ORA-00001. Se algum dia for preciso
-- restaurar um backup que exija gravar um id explícito (ex.: reimportar uma
-- linha de auditoria com o ID_AUDITORIA original), isso é feito de forma
-- explícita e temporária:
--   alter table app_auditoria modify id_auditoria generated by default as identity;
--   -- ... insere com id explícito ...
--   alter table app_auditoria modify id_auditoria generated always as identity;
-- Nunca deixar a tabela em BY DEFAULT como estado permanente.
--
-- Rodar conectado como COMPRAS.
--------------------------------------------------------------------------------

--------------------------------------------------------------------------------
-- 1. APP_DECISAO_PRECO — decisão vigente de margem/preço por produto.
--
-- Uma linha só existe aqui quando existe decisão humana gravada para pelo
-- menos um dos campos. MARGEM_ALVO e MARGEM_ALVO_VAREJO são NULLABLE e SEM
-- DEFAULT de propósito: NULL significa "sem decisão de margem registrada" e
-- é o dbt (fora desta tabela) que aplica o padrão de negócio de 20%
-- (CONTEXTO.md §6 regra 10). Um DEFAULT 0.20 NOT NULL aqui seria uma mentira
-- silenciosa: um INSERT que só grava preço gravaria margem 0,20 junto, e essa
-- margem ficaria indistinguível de uma decisão humana de fato.
--------------------------------------------------------------------------------
declare
    v_existe number;
begin
    select count(*) into v_existe from user_tables where table_name = 'APP_DECISAO_PRECO';
    if v_existe = 0 then
        execute immediate q'[
            create table app_decisao_preco (
                id_produto           number(10)      not null,
                margem_alvo          number(9,6),
                margem_alvo_varejo   number(9,6),
                alt_pv_at_av         number(14,4),
                alt_pv_var_av        number(14,4),
                atualizado_em        timestamp        default systimestamp not null,
                atualizado_por       varchar2(60)     not null,
                constraint pk_app_decisao_preco primary key (id_produto),
                constraint ck_app_decisao_preco_ma
                    check (margem_alvo between -1 and 1),
                constraint ck_app_decisao_preco_mav
                    check (margem_alvo_varejo between -1 and 1),
                constraint ck_app_decisao_preco_pv
                    check (alt_pv_at_av > 0),
                constraint ck_app_decisao_preco_pvv
                    check (alt_pv_var_av > 0)
            )
        ]';
    end if;
end;
/

comment on table app_decisao_preco is
    'Decisão vigente de margem e preço final por produto. Uma linha por SKU com pelo menos um campo decidido; SKU sem linha, ou com MARGEM_ALVO/MARGEM_ALVO_VAREJO NULL, usa o padrão de negócio (margem 20%) aplicado pelo dbt fora desta tabela. Toda alteração aqui deve gravar o valor anterior em APP_DECISAO_PRECO_HIST antes de sobrescrever.';
